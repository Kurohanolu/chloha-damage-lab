const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const sandbox = {module:{exports:{}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../variable-power.js'),'utf8'),sandbox);
const {gyroBall,storedPower,reversal,lastRespects,rageFist} = sandbox.module.exports;
assert.equal(gyroBall(100,100),26);
assert.equal(gyroBall(200,50),7);
assert.equal(gyroBall(50,400),150);
assert.equal(gyroBall(300,1),1);
assert.throws(()=>gyroBall(0,100),/Invalid|Speeds/);
assert.equal(storedPower({}),20);
assert.equal(storedPower({spa:2,spe:1}),80);
assert.equal(storedPower({atk:-2,def:3}),80);
assert.equal(storedPower({accuracy:1,evasion:2}),80);
assert.equal(storedPower({atk:6,def:6,spa:6,spd:6,spe:6,accuracy:6,evasion:6}),860);
assert.throws(()=>storedPower({spa:7}),/Invalid|Speeds/);
assert.equal(reversal(1,100),200);
assert.equal(reversal(4,100),150);
assert.equal(reversal(10,100),80);
assert.equal(reversal(50,100),20);
assert.equal(reversal(100,100),20);
assert.throws(()=>reversal(0,100),/Invalid HP/);
assert.equal(lastRespects(0),50);
assert.equal(lastRespects(1),100);
assert.equal(lastRespects(5),300);
assert.throws(()=>lastRespects(6),/Fainted allies/);
assert.equal(rageFist(0),50);
assert.equal(rageFist(1),100);
assert.equal(rageFist(5),300);
assert.equal(rageFist(6),350);
assert.equal(rageFist(12),350);
assert.throws(()=>rageFist(-1),/Hits taken/);
console.log('v0.182 variable power unit tests PASS');
